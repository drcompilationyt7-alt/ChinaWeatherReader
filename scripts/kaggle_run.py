"""Run one shell command on a Kaggle CPU session and bring its outputs back (2026-11-27).

Why: since ~2026-11-25 GitHub runners cannot download ANY YouTube video (every id: 'no_info' / 'Failed to extract any player
response'), while a Kaggle CPU session downloads the same ids with no cookies (probe run 46054737946). The nightly miners
(ranking / slow-mo / sound) therefore run their MINE step on Kaggle; everything else (state, manifests, publish, gh, secrets)
stays on GitHub.

What goes to Kaggle: the repo commit (cloned from the PUBLIC repo), the --inputs files/dirs (pool state + manifests: public data,
uploaded as a release asset of the public repo and fetched without a token), non-secret --env values. No GitHub token, no
cookies, no API keys ever leave GitHub. What comes back: the --outputs paths (tar in /kaggle/working) + the run log.

  python scripts/kaggle_run.py --slug mine-ranking --inputs /tmp/st output/edit-pools --outputs output/edit-pools/_staged \
      --pip "yt-dlp[default] ..." --env EDIT_THREADS=4 --wait-min 300 -- python core/edit/ranking_pool.py mine-trusted ...

Env: KAGGLE_USERNAME + KAGGLE_API_TOKEN (kaggle CLI), GH_TOKEN + GITHUB_REPOSITORY + GITHUB_SHA (input upload), all on GitHub.
Exit code = the remote command's exit code (or 3 when the session failed / timed out); the outputs are restored either way.
"""
import argparse
import json
import os
import shutil
import subprocess
import sys
import tarfile
import tempfile
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RELEASE = 'kaggle-jobs'      # public release on this repo that carries each job's inputs (deleted after the job)

KERNEL = r'''
# generated by scripts/kaggle_run.py: one job, then only result.tar + run.log stay in /kaggle/working
import json, os, subprocess, sys, tarfile, time, urllib.request
JOB = json.loads(%(job)r)
W = '/kaggle/working'
REPO = '/tmp/repo'
def sh(c, **kw):
    print('+', c if isinstance(c, str) else ' '.join(c), flush=True)
    return subprocess.run(c, shell=isinstance(c, str), **kw)
t0 = time.time()
if JOB['apt']:
    sh('command -v ffmpeg >/dev/null || (apt-get update -qq && apt-get install -y -qq %%s)' %% JOB['apt'])
sh([sys.executable, '-m', 'pip', 'install', '-q'] + JOB['pip'])
os.makedirs(REPO, exist_ok=True)
sh(f"cd {REPO} && git init -q && git fetch -q --depth 1 https://github.com/{JOB['repo']} {JOB['sha']} && git checkout -q FETCH_HEAD", check=True)
if JOB['inputs_url']:
    for k in range(5):
        try:
            urllib.request.urlretrieve(JOB['inputs_url'], '/tmp/inputs.tar.gz'); break
        except Exception as e:
            print('inputs download', e, flush=True); time.sleep(20 * (k + 1))
    with tarfile.open('/tmp/inputs.tar.gz') as t:
        for m in t.getmembers():
            dest = ('/' + m.name[4:]) if m.name.startswith('abs/') else os.path.join(REPO, m.name[4:])
            m.name = os.path.relpath(dest, '/')
            t.extract(m, '/')
env = dict(os.environ, **JOB['env'])
env['PATH'] = os.path.dirname(sys.executable) + ':' + env.get('PATH', '')
if JOB.get('cookies'):
    import glob, shutil
    jars = glob.glob('/kaggle/input/**/cookies.txt', recursive=True)
    if jars:
        shutil.copyfile(jars[0], '/tmp/yt_cookies.txt')
        env.update(YT_COOKIES='/tmp/yt_cookies.txt', YT_SPARE_COOKIES='/tmp/yt_cookies.txt', YT_COOKIE_COPY='1')
        print('cookie jar: on', flush=True)
    else:
        print('cookie jar: missing (running without)', flush=True)
print(f'setup {time.time() - t0:.0f} s; running: {JOB["cmd"]}', flush=True)
with open(os.path.join(W, 'run.log'), 'w') as log:
    p = subprocess.Popen(['bash', '-c', JOB['cmd']], cwd=REPO, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    for line in p.stdout:
        log.write(line); log.flush(); print(line, end='', flush=True)
    rc = p.wait()
with tarfile.open(os.path.join(W, 'result.tar'), 'w') as t:
    for o in JOB['outputs']:
        src = o if o.startswith('/') else os.path.join(REPO, o)
        if os.path.exists(src):
            t.add(src, ('abs' + o) if o.startswith('/') else ('rel/' + o))
json.dump({'rc': rc, 'job': JOB['job_id'], 'minutes': round((time.time() - t0) / 60, 1)}, open(os.path.join(W, 'status.json'), 'w'))
for f in ('/tmp/yt_cookies.txt',):
    if os.path.exists(f):
        os.remove(f)
print('exit', rc, flush=True)
'''


def log(*a):
    print(time.strftime('%H:%M:%S'), '[kaggle_run]', *a, flush=True)


def run(cmd, **kw):
    return subprocess.run(cmd, capture_output=True, text=True, **kw)


def upload_inputs(paths, name):
    """tar the inputs (relative = repo paths, absolute kept absolute) -> a public release asset; returns its URL"""
    paths = [p for p in paths if os.path.exists(p if p.startswith('/') else os.path.join(ROOT, p))]
    if not paths:
        return ''
    tmp = os.path.join(tempfile.gettempdir(), name)
    with tarfile.open(tmp, 'w:gz') as t:
        for p in paths:
            if p.startswith('/'):
                t.add(p, 'abs' + p)
            else:
                t.add(os.path.join(ROOT, p), 'rel/' + p)
    log(f'inputs {name}: {os.path.getsize(tmp) / 1e6:.1f} MB ({", ".join(paths)})')
    repo = os.environ['GITHUB_REPOSITORY']
    if run(['gh', 'release', 'view', RELEASE, '--repo', repo]).returncode:
        run(['gh', 'release', 'create', RELEASE, '--repo', repo, '--title', 'Kaggle job inputs (temporary)', '--notes',
             'Inputs of the Kaggle mining sessions (scripts/kaggle_run.py); each asset is deleted when its job ends.'])
    r = run(['gh', 'release', 'upload', RELEASE, tmp, '--repo', repo, '--clobber'])
    if r.returncode:
        sys.exit(f'inputs upload failed: {r.stderr[:300]}')
    os.remove(tmp)
    return f'https://github.com/{repo}/releases/download/{RELEASE}/{name}'


def push_jar(user, names, slug=''):
    """One of the cookie jars (env vars named in `names`, picked by the run id so the accounts take turns) -> the PRIVATE
    Kaggle dataset <user>/yt-jar (cookies.txt). Never printed; the temp copy is deleted. Returns the dataset ref or None."""
    jars = [n for n in names if (os.environ.get(n) or '').strip()]
    if not jars:
        log('no cookie jar in the environment: running without')
        return None
    # owner 2026-11-27 "use spare and mining alternately": the jar alternates night by night, and two jobs on the same day
    # (different slugs) use different jars
    import datetime as _dt
    import zlib
    k = _dt.datetime.now(_dt.timezone.utc).date().toordinal() + zlib.crc32(slug.encode())
    pick = jars[k % len(jars)]
    ref = f'{user}/yt-jar'
    d = tempfile.mkdtemp()
    try:
        with open(os.path.join(d, 'cookies.txt'), 'w', encoding='utf-8') as f:
            f.write(os.environ[pick].strip() + chr(10))
        json.dump({'title': 'yt-jar', 'id': ref, 'licenses': [{'name': 'other'}]}, open(os.path.join(d, 'dataset-metadata.json'), 'w'))
        exists = run(['kaggle', 'datasets', 'status', ref]).returncode == 0
        r = run(['kaggle', 'datasets', 'version', '-p', d, '-m', os.environ.get('GITHUB_RUN_ID', 'run')] if exists else
                ['kaggle', 'datasets', 'create', '-p', d])
        if r.returncode:
            log('cookie dataset push failed (running without):', (r.stdout + r.stderr).strip()[-200:])
            return None
    finally:
        shutil.rmtree(d, ignore_errors=True)
    for _ in range(20):
        st = (run(['kaggle', 'datasets', 'status', ref]).stdout or '').strip().lower()
        if 'ready' in st:
            break
        time.sleep(15)
    log(f'cookie jar {pick} -> private dataset {ref} ({st or "?"})')
    return ref


def status(ref):
    r = run(['kaggle', 'kernels', 'status', ref])
    return (r.stdout + r.stderr).strip().splitlines()[-1:] or ['?']


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--slug', required=True)
    ap.add_argument('--inputs', nargs='*', default=[])
    ap.add_argument('--outputs', nargs='+', required=True)
    ap.add_argument('--pip', default='')
    ap.add_argument('--apt', default='ffmpeg libgl1 libsndfile1')
    ap.add_argument('--env', action='append', default=[])
    ap.add_argument('--wait-min', type=float, default=300)
    ap.add_argument('--cookie-env', default='', help='comma-separated env var names holding cookie jars (one per run, rotating)')
    ap.add_argument('cmd', nargs=argparse.REMAINDER)
    a = ap.parse_args()
    cmd = ' '.join(a.cmd[1:] if a.cmd[:1] == ['--'] else a.cmd)
    user = os.environ['KAGGLE_USERNAME']
    ref = f'{user}/{a.slug}'
    name = f'{a.slug}-{os.environ.get("GITHUB_RUN_ID", int(time.time()))}.tar.gz'
    url = upload_inputs(a.inputs, name)
    job_id = name
    job = {'job_id': job_id, 'repo': os.environ['GITHUB_REPOSITORY'], 'sha': os.environ['GITHUB_SHA'], 'cmd': cmd, 'inputs_url': url,
           'outputs': a.outputs, 'pip': a.pip.split(), 'apt': a.apt,
           'env': dict(kv.split('=', 1) for kv in a.env)}
    jar = push_jar(user, [x for x in a.cookie_env.split(',') if x], a.slug) if a.cookie_env else None
    job['cookies'] = bool(jar)
    kn = tempfile.mkdtemp()
    with open(os.path.join(kn, 'job.py'), 'w') as f:
        f.write(KERNEL % {'job': json.dumps(job)})
    json.dump({'id': ref, 'title': a.slug, 'code_file': 'job.py', 'language': 'python', 'kernel_type': 'script',
               'is_private': True, 'enable_gpu': False, 'enable_internet': True,
               'dataset_sources': [jar] if jar else [], 'competition_sources': [], 'kernel_sources': []},
              open(os.path.join(kn, 'kernel-metadata.json'), 'w'))
    r = run(['kaggle', 'kernels', 'push', '-p', kn])
    log('push:', (r.stdout + r.stderr).strip()[-300:])
    rc = 3
    if r.returncode == 0:
        t_end = time.time() + a.wait_min * 60
        last = ''
        time.sleep(60)
        while time.time() < t_end:
            s = status(ref)[0]
            if s != last:
                log(s)
                last = s
            if any(k in s for k in ('COMPLETE', 'ERROR', 'CANCEL')):
                break
            time.sleep(60)
        else:
            log(f'not finished after {a.wait_min:.0f} min: fetching what is there')
        out = tempfile.mkdtemp()
        r = run(['kaggle', 'kernels', 'output', ref, '-p', out])
        if r.returncode:
            log('output fetch failed:', (r.stdout + r.stderr)[-300:])
        st = os.path.join(out, 'status.json')
        s = json.load(open(st)) if os.path.exists(st) else {}
        if s.get('job') != job_id:
            # still running, or an older session's output: never restore another job's results
            log(f'no finished output of this job (found {s.get("job")!r}): nothing restored')
            shutil.rmtree(out, ignore_errors=True)
            out = tempfile.mkdtemp()
        else:
            rc = int(s.get('rc', 3))
            log(f'remote exit {rc} after {s.get("minutes")} min')
        lg = os.path.join(out, 'run.log')
        if os.path.exists(lg):
            print(open(lg, encoding='utf-8', errors='replace').read()[-6000:])
        res = os.path.join(out, 'result.tar')
        if os.path.exists(res):
            with tarfile.open(res) as t:
                n = 0
                for m in t.getmembers():
                    dest = ('/' + m.name[4:]) if m.name.startswith('abs/') else os.path.join(ROOT, m.name[4:])
                    if m.isdir():
                        os.makedirs(dest, exist_ok=True)
                        continue
                    os.makedirs(os.path.dirname(dest), exist_ok=True)
                    with t.extractfile(m) as src, open(dest, 'wb') as dst:
                        shutil.copyfileobj(src, dst)
                    n += 1
            log(f'restored {n} output files ({os.path.getsize(res) / 1e6:.0f} MB)')
        else:
            log('no result.tar')
        shutil.rmtree(out, ignore_errors=True)
    if url:
        run(['gh', 'release', 'delete-asset', RELEASE, name, '--repo', os.environ['GITHUB_REPOSITORY'], '--yes'])
    sys.exit(rc)


if __name__ == '__main__':
    main()
