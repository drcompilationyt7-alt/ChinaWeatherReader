"""Theme music beds, generated procedurally (numpy only, original compositions: no samples, no copyrighted songs; licence per
bed in assets/music-beds.json = CC0 / generated by this code).  Each bed is a seamless loop (notes ring over the loop end into its
start), tiled to the video length, and scaled to the RMS of the regular bed so the existing mix / ducking / -14 LUFS master is unchanged.

  moods: tropical (beach), halloween, sleigh (winter), matsuri (festival), romantic (valentine), kawaii (maid), edm (gym),
         dark (villains), lofi (glasses).  The regular bed stays sound.music().
"""
import numpy as np
from scipy.signal import lfilter

SR = 44100
TAU = 2 * np.pi


def _t(d):
    return np.arange(int(SR * d)) / SR


def mid(m):
    return 440.0 * 2 ** ((m - 69) / 12)


def lp(x, fc):
    a = np.exp(-TAU * fc / SR)
    return lfilter([1 - a], [1, -a], x)


def hp(x, fc):
    return x - lp(x, fc)


def env(t, att, dec):
    return np.minimum(1, t / att) * np.exp(-t / dec)


class Loop:
    """Fixed-length buffer; put() wraps what rings past the end back to the start (seamless loop)."""

    def __init__(self, seconds):
        self.n = int(round(seconds * SR))
        self.buf = np.zeros(self.n)

    def put(self, sig, at, gain=1.0):
        i = int(round(at * SR)) % self.n
        k = 0
        while k < len(sig):
            m = min(len(sig) - k, self.n - i)
            self.buf[i:i + m] += gain * sig[k:k + m]
            k += m
            i = 0


# ---- instruments -------------------------------------------------------------
def pluck(f, d=0.5, bright=0.5, dec=0.18):   # ukulele / guitar-like: harmonics fade faster than the fundamental
    t = _t(d)
    s = sum((bright ** (h - 1)) * np.sin(TAU * f * h * t) * np.exp(-t / (dec / (0.6 + 0.4 * h))) for h in range(1, 7))
    return s * np.minimum(1, t / 0.002)


def steelpan(f, d=0.7):
    t = _t(d)
    vib = 1 + 0.004 * np.sin(TAU * 5.5 * t)
    s = np.sin(TAU * f * vib * t) + 0.55 * np.sin(TAU * 2 * f * t) * np.exp(-t / 0.25) + 0.25 * np.sin(TAU * 3.01 * f * t) * np.exp(-t / 0.12)
    return s * env(t, 0.004, 0.32)


def shaker(d=0.07, seed=0):
    r = np.random.default_rng(seed).standard_normal(int(SR * d))
    return hp(r, 5000) * env(_t(d), 0.012, 0.03)


def conga(f=210, d=0.22):
    t = _t(d)
    fr = f * (1 + 0.5 * np.exp(-t / 0.02))
    return np.sin(TAU * np.cumsum(fr) / SR) * np.exp(-t / 0.07) + 0.2 * hp(np.random.default_rng(3).standard_normal(len(t)), 800) * np.exp(-t / 0.01)


def kick(d=0.32, f0=48, sweep=130):
    t = _t(d)
    f = f0 + sweep * np.exp(-t / 0.045)
    return np.sin(TAU * np.cumsum(f) / SR) * np.exp(-t / 0.13)


def snare(d=0.2, seed=1):
    t = _t(d)
    n = hp(np.random.default_rng(seed).standard_normal(len(t)), 1200) * np.exp(-t / 0.07)
    return n + 0.5 * np.sin(TAU * 190 * t) * np.exp(-t / 0.05)


def clap(seed=2):
    t = _t(0.22)
    n = hp(np.random.default_rng(seed).standard_normal(len(t)), 900)
    e = sum(np.exp(-np.maximum(0, t - o) / 0.03) * (t >= o) for o in (0, 0.012, 0.024)) * 0.3 + np.exp(-t / 0.08) * 0.5
    return lp(n * e, 6500)


def hat(seed=0, d=0.05, dec=0.012):
    return hp(np.random.default_rng(seed).standard_normal(int(SR * d)), 6000) * env(_t(d), 0.001, dec)


def organ(f, d, trem=5.0):
    t = _t(d)
    s = sum(a * np.sin(TAU * f * h * t) for h, a in ((1, 1), (2, 0.6), (3, 0.35), (4, 0.2), (6, 0.12)))
    return s * (1 + 0.12 * np.sin(TAU * trem * t)) * np.minimum(1, t / 0.12) * np.minimum(1, (d - t) / 0.2)


def theremin(f1, f2, d):
    t = _t(d)
    f = f1 + (f2 - f1) * np.minimum(1, t / (d * 0.5)) ** 2
    f = f * (1 + 0.012 * np.sin(TAU * 5.8 * t) * np.minimum(1, t / 0.4))
    s = np.sin(TAU * np.cumsum(f) / SR)
    return s * np.minimum(1, t / 0.25) * np.minimum(1, (d - t) / 0.25)


def musicbox(f, d=1.2):
    t = _t(d)
    s = np.sin(TAU * f * t) + 0.5 * np.sin(TAU * 2.76 * f * t) * np.exp(-t / 0.15) + 0.25 * np.sin(TAU * 5.4 * f * t) * np.exp(-t / 0.06)
    return s * env(t, 0.001, 0.45)


def bells(f, d=0.9):   # glockenspiel
    t = _t(d)
    s = np.sin(TAU * f * t) + 0.4 * np.sin(TAU * 4.0 * f * t) * np.exp(-t / 0.2) + 0.2 * np.sin(TAU * 10.0 * f * t) * np.exp(-t / 0.05)
    return s * env(t, 0.001, 0.4)


def sleighbells(d=0.35, seed=0):
    t = _t(d)
    r = np.random.default_rng(seed)
    s = sum(np.sin(TAU * f * t + r.uniform(0, 6)) for f in r.uniform(3800, 8800, 9)) * 0.25
    return s * env(t, 0.003, 0.09) * (1 + 0.5 * np.sin(TAU * 38 * t))


def taiko(d=0.55, f0=58):
    t = _t(d)
    f = f0 + 70 * np.exp(-t / 0.05)
    return (np.sin(TAU * np.cumsum(f) / SR) * np.exp(-t / 0.22) + 0.35 * lp(np.random.default_rng(4).standard_normal(len(t)), 900) * np.exp(-t / 0.03))


def shamisen(f, d=0.4):
    t = _t(d)
    s = sum((0.8 ** (h - 1)) * np.sin(TAU * f * h * t) * np.exp(-t / (0.22 / (0.5 + 0.5 * h))) for h in range(1, 9))
    return (s + 0.25 * hp(np.random.default_rng(5).standard_normal(len(t)), 2500) * np.exp(-t / 0.006)) * np.minimum(1, t / 0.001)


def flute(f1, f2, d):   # shakuhachi-like breathy flute
    t = _t(d)
    f = (f1 + (f2 - f1) * np.minimum(1, t / 0.18)) * (1 + 0.008 * np.sin(TAU * 5 * t) * np.minimum(1, t / 0.4))
    s = np.sin(TAU * np.cumsum(f) / SR) + 0.15 * np.sin(TAU * 2 * np.cumsum(f) / SR)
    s += 0.25 * lp(hp(np.random.default_rng(6).standard_normal(len(t)), 1500), 5000)
    return s * np.minimum(1, t / 0.08) * np.minimum(1, (d - t) / 0.12)


def epiano(f, d=1.0, rhodes=True):
    t = _t(d)
    s = np.sin(TAU * f * t) + 0.35 * np.sin(TAU * 2 * f * t) * np.exp(-t / 0.5) + (0.18 * np.sin(TAU * 7 * f * t) * np.exp(-t / 0.06) if rhodes else 0)
    return s * env(t, 0.004, 0.55) * (1 + 0.06 * np.sin(TAU * 4.5 * t))


def piano(f, d=1.4):
    t = _t(d)
    s = sum((0.55 ** (h - 1)) * np.sin(TAU * f * h * t) * np.exp(-t / (0.9 / h ** 0.6)) for h in range(1, 6))
    return s * np.minimum(1, t / 0.003)


def saw(f, d, a=0.005, dec=None, detune=(1.0,)):
    t = _t(d)
    s = sum(2 * ((f * k * t) % 1) - 1 for k in detune) / len(detune)
    e = np.minimum(1, t / a) * (np.exp(-t / dec) if dec else 1) * np.minimum(1, (d - t) / 0.02)
    return lp(s, 5000) * e


def sq(f, d, dec=0.18):
    t = _t(d)
    return lp(np.sign(np.sin(TAU * f * t)), 3200) * env(t, 0.002, dec) * 0.7


def sub(f, d, dec=None):
    t = _t(d)
    return np.sin(TAU * f * t) * np.minimum(1, t / 0.01) * (np.exp(-t / dec) if dec else 1) * np.minimum(1, (d - t) / 0.03)


def pad(f, d, soft=2200):
    t = _t(d)
    s = sum(np.sin(TAU * f * k * t + p) for k, p in ((1, 0), (1.004, 1), (0.996, 2), (2, 0.5))) / 3
    return lp(s, soft) * np.minimum(1, t / (d * 0.3)) * np.minimum(1, (d - t) / (d * 0.3))


def vinyl(n, seed=7, level=0.02):
    r = np.random.default_rng(seed)
    x = lp(r.standard_normal(n), 3500) * level * 0.4
    pops = np.zeros(n)
    idx = r.integers(0, n, int(n / SR * 6))
    pops[idx] = r.uniform(0.3, 1.0, len(idx)) * level * 8
    return x + lp(pops, 6000)


# ---- scales / helpers ---------------------------------------------------------
def build(spec_fn, bpm, bars, seed, beats=4):
    """Loop of `bars` bars at bpm; spec_fn(L, beat, bars, rng, key) draws into the Loop."""
    beat = 60.0 / bpm
    L = Loop(bars * beats * beat)
    rng = np.random.default_rng(seed)
    spec_fn(L, beat, bars, rng)
    return L.buf


def chord(root, kind):
    return {'maj': (0, 4, 7), 'min': (0, 3, 7), 'maj7': (0, 4, 7, 11), 'min7': (0, 3, 7, 10), 'dom7': (0, 4, 7, 10), 'dim': (0, 3, 6),
            'sus': (0, 5, 7), 'add9': (0, 4, 7, 14), 'min9': (0, 3, 7, 14)}[kind]


# ---- the beds ----------------------------------------------------------------
def marimba(f, d=0.5):
    t = _t(d)
    s = np.sin(TAU * f * t) + 0.3 * np.sin(TAU * 4.0 * f * t) * np.exp(-t / 0.05)
    return s * env(t, 0.002, 0.2)


def bongo(f=330, d=0.14):
    t = _t(d)
    fr = f * (1 + 0.25 * np.exp(-t / 0.015))
    return np.sin(TAU * np.cumsum(fr) / SR) * np.exp(-t / 0.045) + 0.15 * hp(np.random.default_rng(int(f)).standard_normal(len(t)), 1500) * np.exp(-t / 0.006)


def seagull(d=0.7, f0=1500):
    """'kee-ah' call: two gliding, slightly rough harmonic tones."""
    t = _t(d)
    up = np.minimum(1, t / (d * 0.3))
    f = np.where(t < d * 0.3, f0 + 900 * up, f0 + 900 - 800 * np.minimum(1, (t - d * 0.3) / (d * 0.7)))
    f = f * (1 + 0.02 * np.sin(TAU * 38 * t))
    ph = np.cumsum(f) / SR
    s = np.sin(TAU * ph) + 0.45 * np.sin(TAU * 2 * ph) + 0.2 * np.sin(TAU * 3 * ph)
    return s * np.minimum(1, t / 0.03) * np.minimum(1, (d - t) / 0.12) * (0.6 + 0.4 * np.sin(np.pi * t / d))


def ocean(n, swell, seed=5):
    """Soft procedural surf: low-passed noise with a slow swell (period `swell` s, an integer number per loop) + a hissing foam layer."""
    r = np.random.default_rng(seed)
    t = np.arange(n) / SR
    body = lp(r.standard_normal(n), 700)
    foam = hp(lp(r.standard_normal(n), 6500), 1800)
    sw = 0.5 - 0.5 * np.cos(TAU * t / swell)        # 0 at the loop ends, so the noise never clicks at the seam
    crest = np.clip(0.5 - 0.5 * np.cos(TAU * (t / swell - 0.12)), 0, 1)   # foam peaks just after the swell
    return body * (0.25 + sw ** 1.5) * 1.1 + foam * crest ** 3 * 0.5


def _tropical(L, beat, bars, rng):
    """Reggae / tropical-house beach: offbeat ukulele skank, steel pan carrying a catchy major melody, marimba, bongos, shaker,
    one-drop kick, bouncing bass, surf ambience and a few seagulls. ~100 bpm, C major (key varies by seed)."""
    key = int(rng.integers(0, 3))
    roots = [0, 5, 0, 7]                       # I IV I V, twice
    melody = [   # per bar: (beat, scale step in semitones above the key note + octave 5)
        [(0, 12), (0.5, 14), (1, 16), (2, 14), (2.5, 12), (3, 9)],
        [(0, 9), (0.5, 12), (1, 14), (2, 12), (3, 9), (3.5, 7)],
        [(0, 7), (0.5, 9), (1, 12), (2, 16), (2.5, 14), (3, 12)],
        [(0, 14), (1, 12), (1.5, 9), (2, 7), (3, 9)],
    ]
    for b in range(bars):
        r = roots[b % 4]
        base = 60 + key
        t0 = b * 4 * beat
        ch = [0, 4, 7, 12]
        # ukulele: bright strum on every offbeat (the "and"), down-strum spread
        for q in range(4):
            at = t0 + q * beat + beat / 2
            for k, iv in enumerate(ch[:4]):
                L.put(pluck(mid(base + r + iv), 0.32, 0.5, 0.14), at + 0.009 * k, 0.15)
        # steel pan melody (4-bar phrase, second time with a different last bar)
        ph = melody[b % 4]
        for pos, st in ph:
            n = base + st + (0 if not (b >= 4 and b % 4 == 3) else -2)
            L.put(steelpan(mid(n), 0.8), t0 + pos * beat, 0.3)
        # marimba: light eighth-note chord tones underneath
        for q in range(8):
            if q % 2 == 0:
                L.put(marimba(mid(base - 12 + r + ch[(q // 2) % 3]), 0.4), t0 + q * beat / 2, 0.13)
        # one-drop: kick on beat 3 (reggae), bouncing bass root / fifth
        L.put(kick(0.28, 52, 55), t0 + 2 * beat, 0.34)
        L.put(sub(mid(base - 24 + r), beat * 0.9, 0.5), t0, 0.5)
        L.put(sub(mid(base - 24 + r + 7), beat * 0.7, 0.4), t0 + 1.5 * beat, 0.36)
        L.put(sub(mid(base - 24 + r), beat * 0.9, 0.5), t0 + 2.5 * beat, 0.4)
        # bongos + shaker
        for pos, f, g in ((0.5, 330, 0.22), (1.0, 250, 0.2), (2.5, 330, 0.2), (3.0, 250, 0.22), (3.5, 330, 0.18)):
            L.put(bongo(f), t0 + pos * beat, g)
        for q in range(8):
            L.put(shaker(0.07, q % 3), t0 + q * beat / 2, 0.10 if q % 2 else 0.05)
    # ocean waves (one swell every 2 bars); no seagulls (owner)
    L.buf += ocean(L.n, 2 * 4 * beat) * 0.45



def _halloween(L, beat, bars, rng):             # waltz 3/4, A minor-ish: music box + organ + pizzicato + theremin
    key = int(rng.integers(0, 3))
    prog = [(0, 'min'), (0, 'min'), (5, 'maj'), (7, 'maj'), (0, 'min'), (8, 'maj'), (7, 'dom7'), (0, 'min')]
    mb = [0, 3, 7, 12, 15, 12, 7, 3, 8, 7, 3, 0]
    for b in range(bars):
        r, kind = prog[b % 8]
        base = 57 + key + r
        t0 = b * 3 * beat
        ch = chord(r, kind)
        if b % 2 == 0:
            L.put(organ(mid(base - 12), 6 * beat, 4.5), t0, 0.28)
            L.put(organ(mid(base), 6 * beat, 4.5), t0, 0.12)
        L.put(pluck(mid(base - 12 + ch[0]), 0.18, 0.25, 0.07), t0, 0.5)               # pizzicato oom-pah-pah
        for q in (1, 2):
            for k in (1, 2):
                L.put(pluck(mid(base + ch[k]), 0.12, 0.2, 0.05), t0 + q * beat, 0.2)
        for q in range(3):                                                           # creepy music box, minor + a flat 2nd
            n = 81 + key + mb[(b * 3 + q) % len(mb)] + (1 if (b % 4 == 3 and q == 2) else 0)
            L.put(musicbox(mid(n), 1.2), t0 + q * beat, 0.24)
        if b % 4 == 2:                                                               # theremin slide
            n = 76 + key + int(rng.choice([0, 3, 7, 8]))
            L.put(theremin(mid(n), mid(n + int(rng.choice([-2, 1, 3]))), 3 * beat), t0, 0.18)
    L.put(hat(1, 0.3, 0.1), 0, 0.0)


def _sleigh(L, beat, bars, rng):                 # warm, major, glockenspiel + sleigh bells, soft pad
    key = int(rng.integers(0, 3))
    prog = [(0, 'maj'), (9, 'min'), (5, 'maj'), (7, 'dom7')] * 2
    mel = [12, 14, 16, 19, 16, 14, 12, 9, 12, 16, 19, 21, 19, 16, 14, 12]
    for b in range(bars):
        r, kind = prog[b % 8]
        base = 55 + key + r
        t0 = b * 4 * beat
        for k, iv in enumerate(chord(r, kind)[:3]):
            L.put(pad(mid(base + iv), 4 * beat), t0, 0.1)
        L.put(piano(mid(base - 12), 1.2), t0, 0.28)
        L.put(piano(mid(base - 12 + 7), 1.0), t0 + 2 * beat, 0.2)
        for q in range(8):
            if q % 2 == 0 or q in (3, 7):
                L.put(sleighbells(0.3, q % 4), t0 + q * beat / 2, 0.1 if q % 2 else 0.14)
        for q in range(4):
            n = 67 + key + mel[(b * 4 + q) % len(mel)] + (r if rng.random() < 0 else 0)
            L.put(bells(mid(n), 1.0), t0 + q * beat, 0.2)
        L.put(kick(0.22, 52, 40), t0, 0.14)


def _matsuri(L, beat, bars, rng):                # Japanese festival: taiko + shamisen + shakuhachi in the yo scale (D E G A B)
    key = int(rng.integers(0, 3))
    yo = [0, 2, 5, 7, 9, 12, 14, 17, 19]
    for b in range(bars):
        t0 = b * 4 * beat
        base = 50 + key
        for q in range(4):
            L.put(taiko(0.5, 58 if q % 2 == 0 else 70), t0 + q * beat, 0.55 if q == 0 else 0.3)
        for q in (1, 3, 5, 7):
            L.put(taiko(0.12, 100), t0 + q * beat / 2 + (beat / 2 if q in (5, 7) else 0) * 0, 0.12)
        for q in range(8):                                                           # shamisen riff, quick eighths
            if rng.random() < 0.75:
                L.put(shamisen(mid(base + 12 + yo[int(rng.integers(0, 6))]), 0.4), t0 + q * beat / 2, 0.2)
        L.put(sub(mid(base - 12), 2 * beat, 1.0), t0, 0.28)
        if b % 2 == 0:
            n1 = base + 24 + yo[int(rng.integers(2, 7))]
            L.put(flute(mid(n1), mid(n1 + int(rng.choice([-2, 0, 2]))), 3.2 * beat), t0 + 0.5 * beat, 0.2)
        L.put(hat(b, 0.06, 0.02), t0 + 3.5 * beat, 0.05)


def _romantic(L, beat, bars, rng):               # soft ballad, piano arpeggios, pad, maj7 chords
    key = int(rng.integers(0, 3))
    prog = [(0, 'maj7'), (9, 'min7'), (5, 'maj7'), (7, 'dom7')] * 2
    for b in range(bars):
        r, kind = prog[b % 8]
        base = 52 + key + r
        t0 = b * 4 * beat
        ch = chord(r, kind)
        for k, iv in enumerate(ch):
            L.put(pad(mid(base + 12 + iv), 4 * beat, 1800), t0, 0.09)
        for q in range(8):
            iv = (ch[q % len(ch)] if q < 4 else ch[(7 - q) % len(ch)]) + 12
            L.put(piano(mid(base + 12 + iv), 1.6), t0 + q * beat / 2, 0.16)
        L.put(piano(mid(base - 12), 2.4), t0, 0.26)
        if b % 2 == 1:
            L.put(bells(mid(base + 36 + [0, 4, 7][b // 2 % 3]), 1.4), t0 + 2 * beat, 0.08)


def _kawaii(L, beat, bars, rng):                 # bouncy future-pop: square lead, bright pluck, claps, bouncing bass
    key = int(rng.integers(0, 4))
    prog = [(0, 'maj'), (7, 'maj'), (9, 'min'), (5, 'maj')] * 2
    lead = [0, 4, 7, 12, 11, 7, 4, 7, 9, 12, 16, 12, 11, 9, 7, 4]
    for b in range(bars):
        r, kind = prog[b % 8]
        base = 60 + key + r
        t0 = b * 4 * beat
        for q in range(8):
            L.put(sub(mid(base - 24 + (12 if q % 2 else 0)), beat * 0.45, 0.2), t0 + q * beat / 2, 0.4)
            L.put(sq(mid(base + 12 + chord(r, kind)[q % 3]), beat * 0.3, 0.1), t0 + q * beat / 2 + 0.0, 0.07)
        for q in range(4):
            L.put(sq(mid(base + 24 + lead[(b * 4 + q) % 16] - r * 0), beat * 0.9, 0.3), t0 + q * beat, 0.1)
        for q in (0, 2):
            L.put(kick(0.22, 52, 90), t0 + q * beat, 0.4)
        for q in (1, 3):
            L.put(clap(q), t0 + q * beat, 0.3)
        for q in range(8):
            L.put(hat(q % 4, 0.04, 0.01), t0 + q * beat / 2 + beat / 4 * 0, 0.03 if q % 2 else 0.015)
        L.put(bells(mid(base + 36), 0.6), t0 + 3.5 * beat, 0.1)


def _edm(L, beat, bars, rng):                    # 128 bpm workout: four on the floor, offbeat sub, pumping saw stabs, claps
    key = int(rng.integers(0, 5))
    prog = [(0, 'min'), (8, 'maj'), (3, 'maj'), (10, 'maj')] * 2
    for b in range(bars):
        r, kind = prog[b % 8]
        base = 45 + key + r
        t0 = b * 4 * beat
        for q in range(4):
            L.put(kick(0.3, 48, 150), t0 + q * beat, 0.7)
            L.put(sub(mid(base), beat * 0.45, None), t0 + q * beat + beat / 2, 0.45)       # offbeat bass (sidechain feel)
            L.put(hat(q, 0.08, 0.025), t0 + q * beat + beat / 2, 0.05)
            if q in (1, 3):
                L.put(clap(q), t0 + q * beat, 0.4)
        for q in range(8):                                                                # stabs, pumped by the kick
            if q % 2 == 1 or (b % 4 == 3 and q in (4, 6)):
                for iv in chord(r, kind)[:3]:
                    L.put(saw(mid(base + 24 + iv), beat * 0.35, 0.003, 0.2, (1.0, 1.01, 0.99)), t0 + q * beat / 2, 0.06)
        if b % 4 == 3:                                                                    # little riser
            n = int(beat * 2 * SR)
            rs = hp(np.random.default_rng(b).standard_normal(n), 3000) * np.linspace(0, 1, n) ** 2
            L.put(rs, t0 + 2 * beat, 0.12)


def _dark(L, beat, bars, rng):                   # villains: slow, heavy, ominous. Drone, low hits, dissonant strings, metallic stings
    key = int(rng.integers(0, 3))
    prog = [(0, 'min'), (1, 'min'), (0, 'min'), (6, 'dim')] * 2
    for b in range(bars):
        r, kind = prog[b % 8]
        base = 36 + key + r
        t0 = b * 4 * beat
        L.put(sub(mid(base), 4 * beat, None), t0, 0.5)
        L.put(lp(saw(mid(base + 12), 4 * beat, 0.4, None, (1.0, 1.006, 0.994)), 600), t0, 0.35)
        L.put(pad(mid(base + 24 + chord(r, kind)[1]), 4 * beat, 900), t0, 0.12)
        L.put(pad(mid(base + 25), 4 * beat, 900), t0, 0.07 if b % 2 else 0.0)              # a minor 2nd rubbing against it
        L.put(taiko(0.9, 40), t0, 0.7)
        L.put(taiko(0.9, 44), t0 + 2.5 * beat, 0.5)
        if b % 2 == 1:
            L.put(taiko(0.5, 52), t0 + 3.5 * beat, 0.35)
        if b % 4 == 3:
            L.put(bells(mid(base + 48), 2.2), t0 + 1 * beat, 0.07)                             # cold metallic sting


def _lofi(L, beat, bars, rng):                   # chill lo-fi hip hop: swung beat, rhodes 9th chords, mellow bass, vinyl crackle
    key = int(rng.integers(0, 4))
    prog = [(0, 'maj7'), (9, 'min9'), (2, 'min7'), (7, 'dom7')] * 2
    sw = 0.16 * beat
    for b in range(bars):
        r, kind = prog[b % 8]
        base = 52 + key + r
        t0 = b * 4 * beat
        ch = chord(r, kind)
        for k, iv in enumerate(ch):
            L.put(epiano(mid(base + 12 + iv), 3.6, True), t0 + 0.012 * k, 0.1)
        L.put(lp(sub(mid(base - 12), beat * 1.6, 0.5), 400), t0, 0.5)
        L.put(lp(sub(mid(base - 12 + 7), beat * 1.2, 0.4), 400), t0 + 2.5 * beat, 0.35)
        L.put(lp(kick(0.28, 48, 60), 700), t0, 0.5)
        L.put(lp(kick(0.28, 48, 60), 700), t0 + 2.5 * beat + sw, 0.4)
        L.put(lp(snare(0.2, b), 3500), t0 + beat, 0.3)
        L.put(lp(snare(0.2, b + 9), 3500), t0 + 3 * beat, 0.3)
        for q in range(8):
            L.put(lp(hat(q % 4, 0.05, 0.015), 7000), t0 + q * beat / 2 + (sw if q % 2 else 0), 0.07 if q % 2 else 0.1)
        if b % 2 == 1 and rng.random() < 0.8:
            n = base + 24 + ch[int(rng.integers(0, len(ch)))]
            L.put(epiano(mid(n), 1.2, False), t0 + 3 * beat, 0.1)
    L.buf += vinyl(L.n, 7, 0.012)


BEDS = {   # mood -> (builder, bpm, bars, beats per bar)
    'tropical': (_tropical, 100, 8, 4),
    'halloween': (_halloween, 132, 8, 3),
    'sleigh': (_sleigh, 100, 8, 4),
    'matsuri': (_matsuri, 112, 8, 4),
    'romantic': (_romantic, 72, 8, 4),
    'kawaii': (_kawaii, 138, 8, 4),
    'edm': (_edm, 128, 8, 4),
    'dark': (_dark, 66, 8, 4),
    'lofi': (_lofi, 80, 8, 4),
}

_REF = {}
BED_TRIM_DB = {'lofi': -2.2}   # measured with the real duck / voice (scratchpad levels.py): lofi's sustained Rhodes + bass sat 2.2 dB over the regular bed under the voice


def _ref_lufs():
    """Perceived loudness (BS.1770 LUFS) of the regular bed: themed beds are matched to it, so the voice-to-music balance, the ducking
    and the master loudness stay those of the original quiz videos (denser instruments are NOT louder)."""
    if 'v' not in _REF:
        import sound
        _REF['v'] = sound.lufs(sound.music(30.0, seed=1, bpm=112))
    return _REF['v']


def _duck_probe(x):
    """Loudness (LUFS) of the bed as the mix hears it WHILE the narrator speaks: 3 s lines every 6 s, sound.mix's duck curve."""
    import sound
    n = 40 * SR
    x = np.tile(x, int(np.ceil(n / len(x))))[:n]
    sp = np.zeros(n)
    for st in (2, 8, 14, 20, 26, 32):
        sp[int(st * SR):int((st + 3) * SR)] = 0.9 * 0.3   # typical |voice| envelope level (the mix ducks with a 120 ms smoothed |voice|)
    win = int(SR * 0.12)
    env = np.convolve(sp, np.ones(win) / win, mode='same')
    duck = 1 - 0.6 * np.clip(env / 0.08, 0, 1)
    m = sp > 0
    return sound.lufs((x * duck)[m])


def _ref_duck():
    if 'd' not in _REF:
        import sound
        _REF['d'] = _duck_probe(sound.music(40.0, seed=1, bpm=112))
    return _REF['d']


def bed(mood, duration, seed=0):
    """Seamless themed bed of `duration` s, or None when the mood has no own bed."""
    if mood not in BEDS:
        return None
    fn, bpm, bars, beats = BEDS[mood]
    loop = build(fn, bpm, bars, seed, beats)
    loop = loop - loop.mean()
    n = int(SR * duration)
    out = np.tile(loop, int(np.ceil(n / len(loop))))[:n]
    import sound
    out = out * 10 ** ((_ref_lufs() - sound.lufs(out)) / 20.0)
    # ... and the level under the narrator (what the listener compares to the voice) matches the regular bed too
    out = out * 10 ** ((_ref_duck() - _duck_probe(out)) / 20.0)
    out = out * 10 ** (BED_TRIM_DB.get(mood, 0.0) / 20.0)
    fade = int(0.01 * SR)
    out[:fade] *= np.linspace(0, 1, fade)
    return out
